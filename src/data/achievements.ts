/**
 * Get achievement by ID
 */
export function getAchievement(id: string): Achievement | undefined {
  return ACHIEVEMENTS.find(a => a.id === id);
}

/**
 * Get achievements by category
 */
export function getAchievementsByCategory(category: Achievement['category']): Achievement[] {
  return ACHIEVEMENTS.filter(a => a.category === category).sort((a, b) => a.order - b.order);
}

/**
 * Get achievements by trigger
 */
export function getAchievementsByTrigger(trigger: Achievement['trigger']): Achievement[] {
  return ACHIEVEMENTS.filter(a => a.trigger === trigger).sort((a, b) => a.requirement - b.requirement);
}

/**
 * Check if user qualifies for achievements based on stats
 */
export function checkAchievementEligibility(
  stats: Record<string, number>,
  unlockedIds: string[]
): Achievement[] {
  const eligible: Achievement[] = [];
  
  for (const achievement of ACHIEVEMENTS) {
    // Skip if already unlocked
    if (unlockedIds.includes(achievement.id)) continue;
    
    // Skip manual achievements (awarded by admin or special logic)
    if (achievement.trigger === 'manual') continue;
    
    // Check if requirement is met
    const statValue = stats[achievement.trigger] || 0;
    if (statValue >= achievement.requirement) {
      eligible.push(achievement);
    }
  }
  
  return eligible;
}
